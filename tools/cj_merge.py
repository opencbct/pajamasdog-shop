#!/usr/bin/env python3
"""Merge tools/out/cj_items.json into the shop: products/feed.json (cards) + server/catalog.json (prices, CJ variants)
+ sizes_data.js (size charts, in-stock sizes). Keeps hand-picked pd-* items. Re-runnable."""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from cj_names import nice
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX_PRICE = 79.0
items = json.load(open(os.path.join(ROOT, 'tools/out/cj_items.json')))
# 형님's review (11-24): never bring back removed items
_rv = os.path.join(ROOT, 'tools/cj_review.json')
if os.path.exists(_rv): _rm = set(json.load(open(_rv))['remove']); items = [x for x in items if 'cj-' + x['pid'][-8:] not in _rm]
feed = json.load(open(os.path.join(ROOT, 'products/feed.json')))
cat = json.load(open(os.path.join(ROOT, 'server/catalog.json')))

CAT = {'pajamas': 'pajamas', 'acc': 'acc', 'home': 'acc'}
COLOR = {'pajamas': '#5e17eb', 'acc': '#0cc0df', 'home': '#ff3d7f'}
clean_col = lambda c: re.sub(r'\s+', ' ', re.sub(r'[^A-Za-z ]', ' ', c)).strip().title() or 'Classic'

feed = [p for p in feed if not str(p.get('id', '')).startswith('cj-')]
cat['items'] = {k: v for k, v in cat['items'].items() if not k.startswith('cj-')}
sizes_js = open(os.path.join(ROOT, 'sizes_data.js')).read()
SIZES = json.loads(re.search(r'window\.SIZES = (\{.*?\});', sizes_js, re.S).group(1))
STOCK = json.loads(re.search(r'window\.STOCK = (\{.*?\});', sizes_js, re.S).group(1))
for k in [k for k in list(SIZES) + list(STOCK) if k.startswith('cj-')]: SIZES.pop(k, None); STOCK.pop(k, None)

names, added = {}, 0
seen_pid = {v.get('cj_pid') for v in cat['items'].values() if v.get('cj_pid')}   # skip what we already sell by hand
ORDER = ['XXS','XS','S','M','L','XL','XXL','2XL','XXXL','3XL','4XL','5XL']
srt = lambda zs: sorted(zs, key=lambda z: ORDER.index(z) if z in ORDER else 99)
for x in items:
    if x['pid'] in seen_pid or not x.get('img') or x['price'] > MAX_PRICE or not x.get('variants'): continue
    seen_pid.add(x['pid'])
    pid = 'cj-' + x['pid'][-8:]
    colors = [clean_col(c) for c in x['colors']] or ['Classic']
    name = nice(x['cj_name'], x['tag'])
    if len(name.split()) < 2: name = f"{colors[0] if colors[0] not in ('Default', 'Classic') else 'Cozy'} {name}"
    if name in names: name = f"{name} · {colors[0]}"
    names[name] = 1
    sizes = srt([s for s in x['sizes'] if len(s) <= 6])
    prices = sorted(set(x['vprice'].values()))
    feed.append({'id': pid, 'src': 'pd', 'cat': CAT.get(x['cat'], 'acc'), 'name': name,
                 'note': (f"{len(colors)} colors · " if len(colors) > 1 else '') + (f"{sizes[0]}–{sizes[-1]}" if len(sizes) > 1 else 'One size'),
                 'color': COLOR.get(x['cat'], '#5e17eb'), 'img': x['img'],
                 'price': prices[0], 'price_max': prices[-1], 'sizes': sizes, 'colors': colors, 'tags': [x['tag']]})
    cat['items'][pid] = {'name': name, 'price': round(prices[0] * 100), 'cj_pid': x['pid'], 'colors': x['colors'],
                         'sizes': sizes, 'variants': x['variants'],
                         'vprice': {k: round(v * 100) for k, v in x['vprice'].items()}}
    if x.get('chart'): SIZES[pid] = x['chart']
    STOCK[pid] = {'colors': x['colors'], 'avail': {c: [k.split('-', 1)[1] for k in x['variants'] if k.startswith(c + '-')] for c in x['colors']}}
    added += 1

json.dump(feed, open(os.path.join(ROOT, 'products/feed.json'), 'w'), indent=1, ensure_ascii=False)
json.dump(cat, open(os.path.join(ROOT, 'server/catalog.json'), 'w'), indent=1, ensure_ascii=False)
open(os.path.join(ROOT, 'sizes_data.js'), 'w').write(
    '// Size charts (garment cm, from CJ) + sizes in stock per color. Generated by tools/cj_merge.py.\n'
    f'window.SIZES = {json.dumps(SIZES, ensure_ascii=False)};\nwindow.STOCK = {json.dumps(STOCK, ensure_ascii=False)};\n')
print('added', added, '| feed', len(feed), '| catalog', len(cat['items']))
